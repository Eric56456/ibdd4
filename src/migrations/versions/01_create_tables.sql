-- 01_create_tables.sql
-- Создание схемы, таблиц, представлений и триггеров ConcertHub (на основе ЛР №1, ЛР №2, ЛР №3)

-- 1. Подключение криптографического расширения pgcrypto (ЛР №3)
CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- 2. Создание изолированной схемы аудита (ЛР №3)
CREATE SCHEMA IF NOT EXISTS audit;

-- Таблица журнала аудита
CREATE TABLE IF NOT EXISTS audit.main_log (
    log_item_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_type TEXT NOT NULL,
    operation_date TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    user_operator TEXT NOT NULL,
    changed_data TEXT NOT NULL
);

-- Таблица конфиденциальных данных и токенов (ЛР №3)
CREATE TABLE IF NOT EXISTS audit.secret_data (
    "ID" INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT NOT NULL,
    secret_token BYTEA NOT NULL
);

-- 3. Основные таблицы предметной области ConcertHub в схеме public (ЛР №1 и №2)

-- Исполнители
CREATE TABLE IF NOT EXISTS public.artist (
    artist_id SERIAL PRIMARY KEY,
    stage_name TEXT NOT NULL,
    leader_full_name TEXT,
    music_genre TEXT
);

-- Организаторы
CREATE TABLE IF NOT EXISTS public.promoter (
    promoter_id SERIAL PRIMARY KEY,
    company_name TEXT NOT NULL,
    contact_person TEXT,
    contact_phone TEXT
);

-- Площадки
CREATE TABLE IF NOT EXISTS public.venue (
    venue_id SERIAL PRIMARY KEY,
    venue_name TEXT NOT NULL,
    city TEXT NOT NULL,
    address TEXT,
    total_capacity INTEGER
);

-- Секторы площадки
CREATE TABLE IF NOT EXISTS public.hall_sector (
    sector_id SERIAL PRIMARY KEY,
    sector_name TEXT NOT NULL,
    sector_capacity INTEGER NOT NULL,
    sector_type TEXT,
    venue_id INTEGER NOT NULL REFERENCES public.venue(venue_id) ON UPDATE CASCADE ON DELETE CASCADE
);

-- Зрители (с полем birth_date, добавленным в ЛР №2)
CREATE TABLE IF NOT EXISTS public.customer (
    customer_id SERIAL PRIMARY KEY,
    customer_full_name TEXT NOT NULL,
    email TEXT UNIQUE,
    phone_number TEXT,
    birth_date DATE
);

-- Концерты
CREATE TABLE IF NOT EXISTS public.concert (
    concert_id SERIAL PRIMARY KEY,
    program_name TEXT NOT NULL,
    start_datetime TIMESTAMP NOT NULL,
    age_restriction TEXT,
    artist_id INTEGER NOT NULL REFERENCES public.artist(artist_id) ON UPDATE CASCADE ON DELETE CASCADE,
    venue_id INTEGER NOT NULL REFERENCES public.venue(venue_id) ON UPDATE CASCADE ON DELETE CASCADE,
    promoter_id INTEGER NOT NULL REFERENCES public.promoter(promoter_id) ON UPDATE CASCADE ON DELETE CASCADE
);

-- Заказы билетов
CREATE TABLE IF NOT EXISTS public.ticket_order (
    order_id SERIAL PRIMARY KEY,
    order_datetime TIMESTAMP NOT NULL,
    order_status TEXT NOT NULL,
    total_amount NUMERIC(10, 2) NOT NULL,
    customer_id INTEGER NOT NULL REFERENCES public.customer(customer_id) ON UPDATE CASCADE ON DELETE CASCADE
);

-- Билеты
CREATE TABLE IF NOT EXISTS public.ticket (
    ticket_id SERIAL PRIMARY KEY,
    barcode TEXT UNIQUE,
    price NUMERIC(10, 2) NOT NULL,
    ticket_status TEXT NOT NULL,
    concert_id INTEGER NOT NULL REFERENCES public.concert(concert_id) ON UPDATE CASCADE ON DELETE CASCADE,
    sector_id INTEGER NOT NULL REFERENCES public.hall_sector(sector_id) ON UPDATE CASCADE ON DELETE CASCADE,
    order_id INTEGER REFERENCES public.ticket_order(order_id) ON UPDATE CASCADE ON DELETE SET NULL
);

-- 4. Индексы (ЛР №2)
CREATE INDEX IF NOT EXISTS idx_ticket_status ON public.ticket(ticket_status);
CREATE INDEX IF NOT EXISTS idx_concert_datetime ON public.concert(start_datetime);
CREATE INDEX IF NOT EXISTS idx_customer_email ON public.customer(email);
CREATE INDEX IF NOT EXISTS idx_order_status ON public.ticket_order(order_status);
CREATE INDEX IF NOT EXISTS idx_concert_artist_datetime ON public.concert(artist_id, start_datetime);
CREATE INDEX IF NOT EXISTS idx_ticket_concert ON public.ticket(concert_id);

-- 5. Триггерная функция логирования в audit.main_log (ЛР №3)
CREATE OR REPLACE FUNCTION public.logging() RETURNS TRIGGER AS $$
BEGIN
    IF (TG_OP = 'DELETE') THEN
        INSERT INTO audit.main_log (operation_type, operation_date, user_operator, changed_data)
        VALUES ('D', NOW(), current_user, row_to_json(OLD)::text);
    ELSIF (TG_OP = 'UPDATE') THEN
        INSERT INTO audit.main_log (operation_type, operation_date, user_operator, changed_data)
        VALUES ('U', NOW(), current_user, row_to_json(NEW)::text);
    ELSIF (TG_OP = 'INSERT') THEN
        INSERT INTO audit.main_log (operation_type, operation_date, user_operator, changed_data)
        VALUES ('I', NOW(), current_user, row_to_json(NEW)::text);
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

-- Триггеры аудита на таблицы
DROP TRIGGER IF EXISTS logging_exec_artist ON public.artist;
CREATE TRIGGER logging_exec_artist AFTER INSERT OR UPDATE OR DELETE ON public.artist FOR EACH ROW EXECUTE FUNCTION public.logging();

DROP TRIGGER IF EXISTS logging_exec_promoter ON public.promoter;
CREATE TRIGGER logging_exec_promoter AFTER INSERT OR UPDATE OR DELETE ON public.promoter FOR EACH ROW EXECUTE FUNCTION public.logging();

DROP TRIGGER IF EXISTS logging_exec_venue ON public.venue;
CREATE TRIGGER logging_exec_venue AFTER INSERT OR UPDATE OR DELETE ON public.venue FOR EACH ROW EXECUTE FUNCTION public.logging();

DROP TRIGGER IF EXISTS logging_exec_hall_sector ON public.hall_sector;
CREATE TRIGGER logging_exec_hall_sector AFTER INSERT OR UPDATE OR DELETE ON public.hall_sector FOR EACH ROW EXECUTE FUNCTION public.logging();

DROP TRIGGER IF EXISTS logging_exec_customer ON public.customer;
CREATE TRIGGER logging_exec_customer AFTER INSERT OR UPDATE OR DELETE ON public.customer FOR EACH ROW EXECUTE FUNCTION public.logging();

DROP TRIGGER IF EXISTS logging_exec_concert ON public.concert;
CREATE TRIGGER logging_exec_concert AFTER INSERT OR UPDATE OR DELETE ON public.concert FOR EACH ROW EXECUTE FUNCTION public.logging();

DROP TRIGGER IF EXISTS logging_exec_ticket_order ON public.ticket_order;
CREATE TRIGGER logging_exec_ticket_order AFTER INSERT OR UPDATE OR DELETE ON public.ticket_order FOR EACH ROW EXECUTE FUNCTION public.logging();

DROP TRIGGER IF EXISTS logging_exec_ticket ON public.ticket;
CREATE TRIGGER logging_exec_ticket AFTER INSERT OR UPDATE OR DELETE ON public.ticket FOR EACH ROW EXECUTE FUNCTION public.logging();

-- 6. Представления (Views) из ЛР №2

-- Представление 1: Публичная афиша для зрителей
CREATE OR REPLACE VIEW public.view_customer_afisha AS
SELECT
    c.concert_id,
    a.stage_name AS artist,
    c.program_name,
    c.start_datetime,
    c.age_restriction,
    v.city,
    v.venue_name,
    MIN(t.price) AS price_from
FROM public.concert c
JOIN public.artist a ON c.artist_id = a.artist_id
JOIN public.venue v ON c.venue_id = v.venue_id
JOIN public.ticket t ON c.concert_id = t.concert_id
WHERE t.ticket_status = 'Доступен'
GROUP BY c.concert_id, a.stage_name, c.program_name, c.start_datetime,
         c.age_restriction, v.city, v.venue_name;

-- Представление 2: Мои купленные билеты
CREATE OR REPLACE VIEW public.view_customer_my_tickets AS
SELECT
    cust.customer_id,
    cust.customer_full_name,
    t.barcode,
    a.stage_name AS artist,
    c.program_name,
    c.start_datetime,
    v.venue_name,
    hs.sector_name,
    t.price
FROM public.customer cust
JOIN public.ticket_order o ON cust.customer_id = o.customer_id
JOIN public.ticket t ON o.order_id = t.order_id
JOIN public.concert c ON t.concert_id = c.concert_id
JOIN public.artist a ON c.artist_id = a.artist_id
JOIN public.venue v ON c.venue_id = v.venue_id
JOIN public.hall_sector hs ON t.sector_id = hs.sector_id
WHERE o.order_status = 'Оплачен';

-- Представление 3: Мониторинг продаж для организатора
CREATE OR REPLACE VIEW public.view_promoter_sales_monitoring AS
SELECT
    p.company_name AS promoter,
    a.stage_name AS artist,
    c.program_name,
    v.venue_name,
    v.total_capacity,
    COUNT(CASE WHEN t.ticket_status = 'Продан' THEN 1 END) AS tickets_sold,
    ROUND(
        (COUNT(CASE WHEN t.ticket_status = 'Продан' THEN 1 END)::numeric /
        NULLIF(v.total_capacity, 0)) * 100,
        2
    ) AS occupancy_percent,
    COALESCE(SUM(CASE WHEN t.ticket_status = 'Продан' THEN t.price ELSE 0 END), 0) AS total_revenue
FROM public.promoter p
JOIN public.concert c ON p.promoter_id = c.promoter_id
JOIN public.artist a ON c.artist_id = a.artist_id
JOIN public.venue v ON c.venue_id = v.venue_id
LEFT JOIN public.ticket t ON c.concert_id = t.concert_id
GROUP BY p.company_name, a.stage_name, c.program_name, v.venue_name, v.total_capacity;

-- Представление 4: Контроль на входе (Gate-control)
CREATE OR REPLACE VIEW public.view_promoter_gate_control AS
SELECT
    c.concert_id,
    c.start_datetime,
    t.barcode,
    t.ticket_status,
    hs.sector_name,
    hs.sector_type,
    cust.customer_full_name,
    cust.phone_number
FROM public.ticket t
JOIN public.concert c ON t.concert_id = c.concert_id
JOIN public.hall_sector hs ON t.sector_id = hs.sector_id
JOIN public.ticket_order o ON t.order_id = o.order_id
JOIN public.customer cust ON o.customer_id = cust.customer_id
WHERE o.order_status = 'Оплачен';

-- Представление 5: Популярность артистов (статистика)
CREATE OR REPLACE VIEW public.view_artist_popularity AS
SELECT
    a.stage_name AS artist,
    a.music_genre,
    COUNT(DISTINCT c.concert_id) AS total_concerts,
    COUNT(DISTINCT v.city) AS cities_visited,
    SUM(CASE WHEN t.ticket_status = 'Продан' THEN 1 ELSE 0 END) AS total_tickets_sold,
    COALESCE(SUM(CASE WHEN t.ticket_status = 'Продан' THEN t.price ELSE 0 END), 0) AS total_gross
FROM public.artist a
JOIN public.concert c ON a.artist_id = c.artist_id
JOIN public.venue v ON c.venue_id = v.venue_id
LEFT JOIN public.ticket t ON c.concert_id = t.concert_id
GROUP BY a.stage_name, a.music_genre;

-- 7. Создание групповых ролей и назначение привилегий (ЛР №3)
DO $$
BEGIN
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'customer_group_role') THEN
        CREATE ROLE customer_group_role WITH NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE INHERIT;
    END IF;
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'staff_group_role') THEN
        CREATE ROLE staff_group_role WITH NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE INHERIT;
    END IF;
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'admin_group_role') THEN
        CREATE ROLE admin_group_role WITH NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE INHERIT;
    END IF;
END
$$;

-- Настройка прав доступа для customer_group_role (только просмотр концертов и представлений зрителя)
GRANT USAGE ON SCHEMA public TO customer_group_role;
GRANT SELECT ON TABLE public.concert TO customer_group_role;
GRANT SELECT ON TABLE public.artist TO customer_group_role;
GRANT SELECT ON TABLE public.venue TO customer_group_role;
GRANT SELECT ON TABLE public.ticket TO customer_group_role;
GRANT SELECT ON TABLE public.view_customer_afisha TO customer_group_role;
GRANT SELECT ON TABLE public.view_customer_my_tickets TO customer_group_role;
REVOKE ALL ON SCHEMA audit FROM customer_group_role;

-- Настройка прав доступа для staff_group_role (работа со всеми таблицами public и представлениями персонала)
GRANT USAGE ON SCHEMA public TO staff_group_role;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE
    public.artist,
    public.promoter,
    public.venue,
    public.hall_sector,
    public.customer,
    public.concert,
    public.ticket_order,
    public.ticket
TO staff_group_role;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO staff_group_role;
GRANT SELECT ON TABLE
    public.view_customer_afisha,
    public.view_customer_my_tickets,
    public.view_promoter_sales_monitoring,
    public.view_promoter_gate_control,
    public.view_artist_popularity
TO staff_group_role;
REVOKE ALL ON SCHEMA audit FROM staff_group_role;

-- Настройка прав доступа для admin_group_role (полный доступ ко всем схемам, включая audit)
GRANT USAGE ON SCHEMA public, audit TO admin_group_role;
GRANT ALL PRIVILEGES ON ALL TABLES IN SCHEMA public, audit TO admin_group_role;
GRANT ALL PRIVILEGES ON ALL SEQUENCES IN SCHEMA public, audit TO admin_group_role;

-- 8. Создание индивидуальных пользователей для каждой роли (ЛР №3)
DO $$
BEGIN
    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'ivan_customer') THEN
        CREATE USER ivan_customer WITH PASSWORD 'customer';
    ELSE
        ALTER USER ivan_customer WITH PASSWORD 'customer';
    END IF;
    GRANT customer_group_role TO ivan_customer;

    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'petrov_staff') THEN
        CREATE USER petrov_staff WITH PASSWORD 'staff';
    ELSE
        ALTER USER petrov_staff WITH PASSWORD 'staff';
    END IF;
    GRANT staff_group_role TO petrov_staff;

    IF NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'admin_user') THEN
        CREATE USER admin_user WITH PASSWORD 'admin';
    ELSE
        ALTER USER admin_user WITH PASSWORD 'admin';
    END IF;
    GRANT admin_group_role TO admin_user;
END
$$;
